"""
Builds the project from data/ecommerce_data.xlsx:
  1. data/*.csv                     - one clean CSV per sheet
  2. sql/01_create_and_load.sql     - MySQL script: create database, tables and insert all rows
  3. results/query_results.md       - output of every query in sql/02_analysis_queries.sql
     (queries are executed on an in-memory SQLite copy so results can be checked without MySQL)

Usage:  python scripts/build_project.py
"""
import re
import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
EXCEL = ROOT / "data" / "ecommerce_data.xlsx"

# sheet name in Excel -> table name in SQL
TABLES = {
    "customers": "Customers",
    "products": "Products",
    "orders": "Orders",
    "orderdetails": "OrderDetails",
}

SCHEMA = """
CREATE TABLE Customers (
    customer_id INT PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    location    VARCHAR(50)  NOT NULL
);

CREATE TABLE Products (
    product_id INT PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    category   VARCHAR(50)  NOT NULL,
    price      DECIMAL(10,2) NOT NULL
);

CREATE TABLE Orders (
    order_id     INT PRIMARY KEY,
    order_date   DATE NOT NULL,
    customer_id  INT  NOT NULL,
    total_amount DECIMAL(12,2) NOT NULL,
    FOREIGN KEY (customer_id) REFERENCES Customers(customer_id)
);

-- No primary key here: the source data has repeated (order_id, product_id) lines,
-- and order totals in Orders include every line, so all rows are kept.
CREATE TABLE OrderDetails (
    order_id       INT NOT NULL,
    product_id     INT NOT NULL,
    quantity       INT NOT NULL,
    price_per_unit DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (order_id)   REFERENCES Orders(order_id),
    FOREIGN KEY (product_id) REFERENCES Products(product_id)
);
"""


def load_sheets():
    sheets = pd.read_excel(EXCEL, sheet_name=None)
    frames = {}
    for sheet, table in TABLES.items():
        df = sheets[sheet].dropna(axis=1, how="all").dropna(how="all")
        if "order_date" in df:
            df["order_date"] = pd.to_datetime(df["order_date"]).dt.strftime("%Y-%m-%d")
        frames[table] = df
    return frames


def sql_value(v):
    if isinstance(v, str):
        return "'" + v.replace("\\", "\\\\").replace("'", "''") + "'"
    return str(v)


def write_load_script(frames):
    out = [
        "/* =====================================================================",
        "   E-COMMERCE SQL CASE STUDY  -  CREATE DATABASE + LOAD DATA (MySQL 8.0)",
        "   Generated by scripts/build_project.py from data/ecommerce_data.xlsx",
        "   MySQL Workbench: File > Open SQL Script > this file > Execute (lightning icon)",
        "   ===================================================================== */",
        "",
        "DROP DATABASE IF EXISTS ecommerce_db;",
        "CREATE DATABASE ecommerce_db;",
        "USE ecommerce_db;",
        SCHEMA,
    ]
    for table, df in frames.items():
        cols = ", ".join(df.columns)
        rows = [
            "(" + ", ".join(sql_value(v) for v in row) + ")"
            for row in df.itertuples(index=False)
        ]
        out.append(f"-- {table}: {len(rows)} rows")
        out.append(f"INSERT INTO {table} ({cols}) VALUES\n" + ",\n".join(rows) + ";\n")
    out.append("-- Check: row counts")
    out.append(
        "SELECT 'Customers' AS table_name, COUNT(*) AS total_rows FROM Customers\n"
        "UNION ALL SELECT 'Products', COUNT(*) FROM Products\n"
        "UNION ALL SELECT 'Orders', COUNT(*) FROM Orders\n"
        "UNION ALL SELECT 'OrderDetails', COUNT(*) FROM OrderDetails;\n"
    )
    (ROOT / "sql" / "01_create_and_load.sql").write_text("\n".join(out), encoding="utf-8")


def to_sqlite(sql):
    """Translate the few MySQL-only bits used in the queries to SQLite."""
    sql = re.sub(r"DATE_FORMAT\(([\w.]+),\s*'%Y-%m'\)", r"strftime('%Y-%m', \1)", sql)
    return sql


def run_queries(frames):
    con = sqlite3.connect(":memory:")
    for table, df in frames.items():
        df.to_sql(table, con, index=False)

    text = (ROOT / "sql" / "02_analysis_queries.sql").read_text(encoding="utf-8")
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    report = ["# Query Results", "",
              "Output of every query in `sql/02_analysis_queries.sql` "
              "(generated by `scripts/build_project.py`).", ""]
    for stmt in text.split(";"):
        lines = [l for l in stmt.strip().splitlines()]
        title = next((l[3:].strip() for l in lines if re.match(r"-- Q\d", l)), None)
        body = "\n".join(l for l in lines if not l.strip().startswith("--")).strip()
        if not body or body.upper().startswith("USE "):
            continue
        df = pd.read_sql_query(to_sqlite(body), con)
        report += [f"## {title}", "", df.astype(object).where(df.notna(), None).to_markdown(index=False, missingval="NULL"), ""]
        print(f"OK  {title}  ({len(df)} rows)")
    (ROOT / "results" / "query_results.md").write_text("\n".join(report), encoding="utf-8")


def main():
    frames = load_sheets()
    for table, df in frames.items():
        df.to_csv(ROOT / "data" / f"{table.lower()}.csv", index=False)
    write_load_script(frames)
    run_queries(frames)


if __name__ == "__main__":
    main()
